// Standards-compatible uncompressed ZIP, bounded to the existing 32 KiB Forge artifact limit.
const enc=new TextEncoder();
function crc32(bytes){let crc=0xffffffff;for(const b of bytes){crc^=b;for(let bit=0;bit<8;bit++)crc=(crc>>>1)^((crc&1)?0xedb88320:0);}return (crc^0xffffffff)>>>0;}
export function zipProject(files){
 if(!Array.isArray(files)||files.length<1||files.length>20)throw Error("Project must contain 1–20 files.");
 const chunks=[],central=[],seen=new Set();let offset=0,centralSize=0;
 function header(size){const bytes=new Uint8Array(size),v=new DataView(bytes.buffer);return {bytes,u16:(p,x)=>v.setUint16(p,x,true),u32:(p,x)=>v.setUint32(p,x,true)};}
 for(const file of files){
  if(!file||typeof file.path!=="string"||file.path.length>100||!file.path.split("/").every(p=>/^[A-Za-z0-9][A-Za-z0-9._-]{0,50}$/.test(p)&&p!=="."&&p!=="..")||seen.has(file.path.toLowerCase())||typeof file.content!=="string")throw Error("Unsafe or duplicate project filename.");
  seen.add(file.path.toLowerCase());const name=enc.encode(file.path),data=enc.encode(file.content),crc=crc32(data);
  const h=header(30);h.u32(0,0x04034b50);h.u16(4,20);h.u16(6,0x800);h.u16(12,33);h.u32(14,crc);h.u32(18,data.length);h.u32(22,data.length);h.u16(26,name.length);
  const c=header(46);c.u32(0,0x02014b50);c.u16(4,20);c.u16(6,20);c.u16(8,0x800);c.u16(14,33);c.u32(16,crc);c.u32(20,data.length);c.u32(24,data.length);c.u16(28,name.length);c.u32(42,offset);
  chunks.push(h.bytes,name,data);central.push(c.bytes,name);offset+=30+name.length+data.length;centralSize+=46+name.length;
  if(offset+centralSize+22>32768)throw Error("Project archive exceeds 32 KiB.");
 }
 const end=header(22);end.u32(0,0x06054b50);end.u16(8,files.length);end.u16(10,files.length);end.u32(12,centralSize);end.u32(16,offset);
 const out=new Uint8Array(offset+centralSize+22);let pos=0;for(const part of [...chunks,...central,end.bytes]){out.set(part,pos);pos+=part.length;}return out;
}

// Read only the small, uncompressed ZIP subset generated by the Forge. No filesystem extraction.
export function readProjectZip(bytes){
 if(!(bytes instanceof Uint8Array)||bytes.length<22||bytes.length>32768)throw Error("Expected a ZIP archive of 22–32768 bytes.");
 const v=new DataView(bytes.buffer,bytes.byteOffset,bytes.byteLength),u16=p=>v.getUint16(p,true),u32=p=>v.getUint32(p,true),dec=new TextDecoder("utf-8",{fatal:true}),end=bytes.length-22;
 if(u32(end)!==0x06054b50||u16(end+4)||u16(end+6)||u16(end+20))throw Error("Unsupported ZIP directory.");
 const count=u16(end+10),size=u32(end+12),central=u32(end+16);
 if(!count||count>20||u16(end+8)!==count||central+size!==end)throw Error("Invalid ZIP directory bounds.");
 const files=[],seen=new Set();let p=0,c=central;
 for(let i=0;i<count;i++){
  if(p+30>central||c+46>end||u32(p)!==0x04034b50||u32(c)!==0x02014b50)throw Error("Invalid ZIP headers.");
  const flags=u16(p+6),method=u16(p+8),crc=u32(p+14),length=u32(p+22),nameLength=u16(p+26),extra=u16(p+28);
  if(flags!==0x800||method||extra||u32(p+18)!==length||u16(c+8)!==flags||u16(c+10)!==method||u32(c+16)!==crc||u32(c+20)!==length||u32(c+24)!==length||u16(c+28)!==nameLength||u16(c+30)||u16(c+32)||u16(c+34)||u32(c+42)!==p)throw Error("Unsupported or inconsistent ZIP headers.");
  const start=p+30+nameLength,finish=start+length,next=c+46+nameLength;
  if(!nameLength||nameLength>100||finish>central||next>end)throw Error("Invalid ZIP entry bounds.");
  const path=dec.decode(bytes.subarray(p+30,start)),centralPath=dec.decode(bytes.subarray(c+46,next));
  if(path!==centralPath||!path.split("/").every(s=>/^[A-Za-z0-9][A-Za-z0-9._-]{0,50}$/.test(s)&&s!=="."&&s!=="..")||seen.has(path.toLowerCase()))throw Error("Unsafe or duplicate ZIP entry.");
  seen.add(path.toLowerCase());const data=bytes.subarray(start,finish);if(crc32(data)!==crc)throw Error("ZIP entry CRC mismatch.");
  const content=dec.decode(data);files.push({path,content,bytes:length,crc32:crc.toString(16).padStart(8,"0")});p=finish;c=next;
 }
 if(p!==central||c!==end)throw Error("Unexpected data outside ZIP entries.");
 return files;
}
