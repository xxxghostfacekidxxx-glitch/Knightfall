import {readFileSync} from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const read=p=>readFileSync(p,"utf8");
const gameRoot="public/arcade/hosted/";
const conway=read(gameRoot+"cinder-life/index.html");
const board=read(gameRoot+"roads-of-cinder/index.html");
assert.match(conway,/Conway's Game of Life/);
assert.match(conway,/canvas id="board"/);
assert.match(board,/roads-of-cinder\/engine.js/);
assert.match(board,/roads-of-cinder\/view.js/);
for(const file of ["engine.js","view.js"])new vm.Script(read(gameRoot+"roads-of-cinder/"+file));
const ctx={Math:Object.create(Math)};
ctx.Math.random=()=>.12;vm.runInNewContext(read(gameRoot+"roads-of-cinder/engine.js"),ctx);
const {RoadsGame,PATH}=ctx.RoadsOfCinder;
assert.ok(PATH.length>=60,"life journey board has 60+ distinct spaces");
const game=new RoadsGame({names:["Ash","Ember","Ruin","Cinder"],rng:()=>.12});
assert.equal(game.players.length,4);assert.equal(game.pending.kind,"path");
assert.equal(game.spin(),null,"must choose a career before spinning");
assert.equal(game.choose("college"),true);
assert.equal(game.player().debt,45000);
assert.equal(game.pending.kind,"career");
assert.equal(game.options().some(x=>x.id==="engineer"),true);
assert.equal(game.choose("engineer"),true);
assert.equal(game.current,1);assert.equal(game.pending.kind,"path");
assert.equal(game.choose("work"),true);
assert.equal(game.options().some(x=>x.id==="engineer"),false,"work path cannot take degree-only jobs");
assert.equal(game.choose("mechanic"),true);
assert.equal(game.choose("work"),true);assert.equal(game.choose("artist"),true);
assert.equal(game.choose("college"),true);assert.equal(game.choose("pilot"),true);
assert.equal(game.pending,null);
const spin=game.spin();assert.ok(spin>=1&&spin<=10);
assert.equal(game.current,1,"turn passes after a simple payday");
const saved=game.snapshot();const resumed=new RoadsGame();
assert.equal(resumed.restore(saved),true);assert.equal(resumed.players.length,4);
assert.equal(resumed.current,game.current);
assert.equal(resumed.restore({...saved,players:[{pos:-1}]}),false,"reject malformed saves");
const forced=new RoadsGame({rng:()=>.999});
forced.choose("work");forced.choose("mechanic");forced.choose("work");forced.choose("artist");
forced.players[0].pos=59;forced.players[1].pos=59;
forced.spin();assert.equal(forced.pending.kind,"retire");
forced.choose("quiet");assert.equal(forced.players[0].retired,true);assert.equal(forced.finished,false);
forced.spin();assert.equal(forced.pending.kind,"retire");forced.choose("legacy");
assert.equal(forced.finished,true);assert.equal(forced.results().length,2);
assert.ok(forced.results()[0].netWorth>=forced.results()[1].netWorth);
console.log("Roads of Cinder: 4-player setup, school/career restrictions, spin, retirement, winner, and resume PASS");
console.log("Cinder Life cellular automaton preserved PASS");